function simpleCard(input: {
  id: string;
  name: string;
  network: "visa" | "mastercard";
  family: "everyday" | "travel" | "low_interest";
  url: string;
  image: string | null;
  program: string;
  fee: number;
  extraFee: number | null;
  apr: number;
  aprLabel: string;
  income: ReturnType<typeof orIncome> | null;
  eligibility: string;
  sourceId: string;
  rules: RewardRule[];
  offers: WelcomeOffer[];
  benefits: string[];
  rankEligible?: boolean;
  unrankedReason?: string | null;
  verification?: TermVersion["verificationStatus"];
  rewardsAssumption?: string | null;
  cashAdvanceApr?: number | null;
}): (typeof catalog.cards)[number] {
  return {
    id: input.id,
    slug: input.id,
    name: input.name,
    network: input.network,
    family: input.family,
    currency: "CAD",
    productUrl: input.url,
    activeStatus: "active",
    image: input.image,
    rankEligible: input.rankEligible ?? true,
    unrankedReason: input.unrankedReason ?? null,
    rewardsAssumption: input.rewardsAssumption ?? null,
    termVersions: [
      version({
        id: `${input.id}-current`,
        effectiveFrom: null,
        effectiveTo: null,
        annualFeeCad: input.fee,
        additionalCardFeeCad: input.extraFee,
        purchaseApr: input.apr,
        aprLow: null,
        aprHigh: null,
        aprLabel: input.aprLabel,
        cashAdvanceApr: input.cashAdvanceApr ?? 0.2299,
        rewardProgramId: input.program,
        eligibility: input.eligibility,
        incomeRule: input.income,
        vipRebateCad: null,
        verificationStatus: input.verification ?? "verified",
        verifiedAt: verified,
        sourceId: input.sourceId,
        rules: input.rules,
        offers: input.offers,
        benefits: input.benefits,
      }),
    ],
  };
}

