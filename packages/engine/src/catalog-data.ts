function rule(
  id: string,
  categories: Category[] | ["*"],
  earnUnit: EarnUnit,
  earnRate: number,
  priority: number,
  sourceId: string,
  extra: Partial<RewardRule> = {},
): RewardRule {
  return {
    id,
    categories,
    slice: "any",
    earnUnit,
    earnRate,
    fallbackRate: null,
    tierLowerCad: 0,
    tierUpperCad: null,
    capGroupId: null,
    resetPeriod: "none",
    priority,
    conditions: extra.conditions ?? "",
    sourceId,
    ...extra,
  };
}

